def test_no_seat_is_systematically_doomed(card_db):
    """The bug this catches produced a completely plausible wrong answer.

    Every bot broke ties on "who to attack" by lowest player id. On turn one
    nobody is distinguishable, so all three opponents attacked seat zero in
    every game of every run, and a goldfish measuring seat zero read a 0% win
    rate across 200 games. Nothing crashed and no test failed - the deck just
    looked terrible.
    """
    config = RunConfig(decklists=(DECK,) * 4, games=48, run_seed=17, workers=1)
    winners = collections.Counter(r.winner for r in run(config).records)
    decided = sum(count for seat, count in winners.items() if seat is not None)
    assert decided >= 12, "too few decided games to judge"

    for seat in range(4):
        assert winners[seat] > 0, f"seat {seat} won nothing of {decided}: {winners}"


def test_the_bot_aims_removal_at_opponents(card_db):
    """Otherwise it Murders its own creatures.

    The engine offers every legal target and the default choice is the first
    one, which is as likely to be yours as theirs.
    """
    from harness import ScriptedAbilities, make_board

    from mtgfish.ai.simple import SimpleAgent
    from mtgfish.rules.cr600_spells_and_abilities.abilities import Ability
    from mtgfish.rules.cr600_spells_and_abilities.effects import Effect, EffectKind
    from mtgfish.rules.kernel.enums import CardType
    from mtgfish.rules.kernel.query import ObjectFilter

    scripts = ScriptedAbilities()
    board = make_board(card_db, scripts)
    creatures = ObjectFilter(types_all=CardType.CREATURE)
    scripts.add(
        "Murder",
        Ability.spell(
            Effect(EffectKind.DESTROY, targets=creatures, is_targeted=True),
            text="Destroy target creature.",
        ),
    )

    spell = board.hand("Murder", controller=0)
    mine = board.play("Grizzly Bears", controller=0)
    theirs = board.play("Serra Angel", controller=1)

    agent = SimpleAgent()
    chosen = agent.choose_targets(board.game, 0, spell.id, [[mine.id, theirs.id]])
    assert chosen == ((theirs.id,),), "the bot should not kill its own creature"


def test_the_bot_holds_mana_on_other_players_turns(card_db):
    """CR gives instant speed for a reason, and a bot that spends the moment
    it can is playing sorcery speed badly - it taps out in an opponent's
    upkeep and cannot cast its own four-drop."""
    from harness import ScriptedAbilities, make_board

    from mtgfish.ai.simple import SimpleAgent
    from mtgfish.rules.cr100_game_concepts.cr117_priority import Action, ActionKind
    from mtgfish.rules.kernel.enums import Phase, Step

    board = make_board(card_db, ScriptedAbilities())
    trick = board.hand("Giant Growth", controller=0)
    cast = Action(ActionKind.CAST_SPELL, source=trick.id)

    agent = SimpleAgent()
    board.game.active_player = 1
    board.game.phase = Phase.BEGINNING
    board.game.step = Step.UPKEEP
    assert agent._worth_casting_now(board.game, 0, [cast]) == []

    board.game.active_player = 0
    board.game.phase = Phase.PRECOMBAT_MAIN
    board.game.step = Step.MAIN
    assert agent._worth_casting_now(board.game, 0, [cast]) == [cast]


def test_a_targeted_spell_can_be_cast_at_all(card_db):
    """CR 601.2c: targets are chosen while casting.

    They used to have to be supplied on the Action, which no bot did - so
    every removal spell, burn spell and targeted draw spell in every deck was
    silently uncastable and the simulator reported combat damage as the only
    way anyone ever won.
    """
    from harness import ScriptedAbilities, make_board

    from mtgfish.rules.cr100_game_concepts.cr117_priority import Action, ActionKind
    from mtgfish.rules.cr600_spells_and_abilities.abilities import Ability
    from mtgfish.rules.cr600_spells_and_abilities.cr601_casting import cast_spell
    from mtgfish.rules.cr600_spells_and_abilities.effects import Effect, EffectKind
    from mtgfish.rules.kernel.enums import CardType
    from mtgfish.rules.kernel.query import ObjectFilter

    scripts = ScriptedAbilities()
    board = make_board(card_db, scripts)
    scripts.add(
        "Murder",
        Ability.spell(
            Effect(
                EffectKind.DESTROY,
                targets=ObjectFilter(types_all=CardType.CREATURE),
                is_targeted=True,
            ),
            text="Destroy target creature.",
        ),
    )
    from mtgfish.ai.simple import SimpleAgent

    board.game.agents[0] = SimpleAgent()
    spell = board.hand("Murder", controller=0)
    victim = board.play("Grizzly Bears", controller=1)

    from mtgfish.rules.cr100_game_concepts.cr106_mana import ManaKind
    from mtgfish.rules.kernel.enums import LETTER_TO_COLOR

    board.game.player(0).mana_pool.add(ManaKind(LETTER_TO_COLOR["B"]), 3)

    stack_object = cast_spell(
        board.game, 0, Action(ActionKind.CAST_SPELL, source=spell.id)
    )
    assert stack_object.targets == ((victim.id,),)


