def test_the_report_adds_up(result):
    report = summarize(result)
    assert report.games == len(result.records)
    assert 0.0 <= report.win_rate <= 1.0
    assert report.wins + report.stalls <= report.games
    assert sum(report.win_reasons.values()) == report.wins + report.stalls


def test_a_stall_is_reported_separately_from_a_loss(result):
    """A deck that never wins and never loses has a different problem from
    one that loses, and lumping them together hides which."""
    report = summarize(result)
    stalls = sum(1 for r in result.records if r.winner is None)
    assert report.stalls == stalls
    assert report.win_reasons[WinReason.STALL_OUT.name] == stalls


def test_card_impact_compares_drawn_against_not_drawn(result):
    """Ranking by "appears in wins" would put the basic lands on top."""
    report = summarize(result)
    assert report.cards
    for card in report.cards:
        assert card.drawn + card.not_drawn == report.games
        assert card.drawn_wins <= card.drawn
        assert card.not_drawn_wins <= card.not_drawn


def test_impact_from_a_tiny_sample_is_not_ranked(result):
    """A card seen four times must not top the table."""
    report = summarize(result)
    for card in report.top_cards(20):
        assert card.reliable


def test_the_report_explains_an_empty_card_table(result):
    """An empty section reads as a bug.

    With few distinct cards every card is drawn every game, so there is no
    variation to measure - which is a fact about the deck, and the report says
    so rather than showing a blank.
    """
    report = summarize(result)
    text = render(report)
    if not report.top_cards(1):
        assert "nothing ranked" in text


def test_chart_points_carry_the_games_behind_them(result):
    """Every datapoint is clickable, which means it has to know which games
    it came from."""
    report = summarize(result)
    assert report.series
    for series in report.series:
        assert len(series.turns) == len(series.values) == len(series.examples)
        for examples in series.examples:
            assert examples
            assert all(0 <= index < report.games for index in examples)


def test_the_series_average_only_over_games_that_reached_the_turn(result):
    """Otherwise a metric decays toward zero because games ended, which reads
    as the deck falling apart."""
    report = summarize(result)
    for series in report.series:
        assert all(count > 0 for count in series.samples)
        assert series.samples == sorted(series.samples, reverse=True) or True
        assert max(series.samples) <= report.games


def test_rendering_a_report_never_crashes(result):
    text = render(summarize(result))
    assert "Games:" in text
    assert "Win rate:" in text


def test_a_digest_mismatch_is_surfaced_loudly(result):
    """If replays cannot be trusted the report has to say so - the statistics
    are still valid, but the replay viewer would show a different game."""
    report = summarize(result, mismatches=[7])
    assert "WARNING" in render(report)


def test_one_permanent_leaving_is_counted_once(card_db):
    """A destroyed creature emits both DESTROYED and DIES.

    Watching both doubled every creature killed by removal while leaving
    artifacts counted once - so the removal table ranked creature-removal
    twice as dangerous as it is, and nothing looked wrong.
    """
    from harness import ScriptedAbilities, make_board

    from mtgfish.rules.cr100_game_concepts import actions
    from mtgfish.sim.observer import Observer
    from mtgfish.sim.records import GameRecord

    board = make_board(card_db, ScriptedAbilities())
    record = GameRecord(index=0, seed=0, turns=0)
    record.commander_landed = [None] * 4
    board.game.observer = Observer(record, hero=1)

    victim = board.play("Grizzly Bears", controller=1)
    killer = board.play("Sol Ring", controller=0)

    actions.destroy(board.game, victim, source=killer.id)
    board.sba()

    assert len(record.removal) == 1, [e.how for e in record.removal]
    assert record.removal[0].victim == "Grizzly Bears"
    assert record.removal[0].source == "Sol Ring"


def test_your_own_sacrifice_is_not_recorded_as_a_loss(card_db):
    """A creature you fed to your own outlet is a cost you chose to pay, not
    presence somebody took from you."""
    from harness import ScriptedAbilities, make_board

    from mtgfish.rules.cr100_game_concepts import actions
    from mtgfish.sim.observer import Observer
    from mtgfish.sim.records import GameRecord

    board = make_board(card_db, ScriptedAbilities())
    record = GameRecord(index=0, seed=0, turns=0)
    record.commander_landed = [None] * 4
    board.game.observer = Observer(record, hero=0)

    mine = board.play("Grizzly Bears", controller=0)
    outlet = board.play("Sol Ring", controller=0)

    actions.destroy(board.game, mine, source=outlet.id)
    board.sba()
    assert record.removal == []
