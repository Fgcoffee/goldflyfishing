"""The simulator: determinism, the records, and the report.

Determinism is the load-bearing property here. Replays are not stored - they
are regenerated by replaying a seed - so if a seed does not determine a game,
every replay in the product shows a different game from the one the numbers
came from. Several tests here exist only to make that impossible to break
quietly.

The rest are regression guards for bugs that produced *plausible* numbers,
which are the dangerous kind: a 0% win rate looks like a bad deck, not a bad
tie-break.
"""

from __future__ import annotations

import collections

import pytest

from mtgfish.sim import (
    RunConfig,
    WinReason,
    render,
    replay_game,
    run,
    summarize,
    verify,
)

DECK = """// Commander
1 Ezuri, Renegade Leader
// Deck
34 Forest
10 Llanowar Elves
10 Elvish Mystic
15 Grizzly Bears
15 Runeclaw Bear
8 Giant Growth
7 Sol Ring
"""


@pytest.fixture(scope="module")
def config(card_db):
    card_db.registry()
    return RunConfig(decklists=(DECK,) * 4, games=24, run_seed=3, workers=1)


@pytest.fixture(scope="module")
def result(config):
    return run(config)


