def test_the_same_seed_gives_the_same_game(config):
    """The property the whole replay design rests on."""
    from mtgfish.sim.runner import play_one

    first = play_one(config, 5)
    second = play_one(config, 5)
    assert first.digest == second.digest
    assert first.turns == second.turns
    assert first.winner == second.winner


def test_a_games_seed_does_not_depend_on_how_many_games_ran(card_db):
    """Game 12 of a 20-game run must be game 12 of a 10,000-game run.

    Derived arithmetically from the run seed and the index rather than drawn
    from a stream, so a datapoint can be replayed without replaying everything
    before it - which is what makes a chart clickable at all.
    """
    small = RunConfig(decklists=(DECK,) * 4, games=20, run_seed=9)
    large = RunConfig(decklists=(DECK,) * 4, games=10_000, run_seed=9)
    assert small.seed_for(12) == large.seed_for(12)


def test_neighbouring_games_are_not_neighbouring_seeds(card_db):
    """Consecutive indices must not produce visibly similar shuffles."""
    config = RunConfig(decklists=(DECK,) * 4, games=100, run_seed=1)
    seeds = [config.seed_for(index) for index in range(20)]
    assert len(set(seeds)) == 20
    gaps = {abs(seeds[i + 1] - seeds[i]) for i in range(19)}
    assert len(gaps) > 15, "seeds look like a counter"


def test_verify_finds_no_mismatches(config, result):
    """The run's own determinism check.

    A non-empty result means something read unordered state, and the report
    has to say so rather than showing a replay that is not the game measured.
    """
    assert verify(config, result, sample=4) == []


def test_replaying_reproduces_the_recorded_game(config, result):
    """A replay is the same game, not a similar one."""
    record = result.records[3]
    view = replay_game(config, 3)
    assert view.seed == record.seed
    assert view.turns == record.turns
    assert view.winner == record.winner
    assert view.frames, "a replay with no frames is not a replay"


def test_running_in_parallel_gives_the_same_records(card_db):
    """Workers must not change the answer, only the wall clock."""
    serial = RunConfig(decklists=(DECK,) * 4, games=8, run_seed=4, workers=1)
    parallel = RunConfig(decklists=(DECK,) * 4, games=8, run_seed=4, workers=4)

    one = run(serial)
    two = run(parallel)
    assert [r.index for r in two.records] == list(range(8)), "results out of order"
    assert [r.digest for r in one.records] == [r.digest for r in two.records]


