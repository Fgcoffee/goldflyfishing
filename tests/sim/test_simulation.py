def test_games_finish_and_record_a_winner(result):
    assert result.records
    decided = [r for r in result.records if r.winner is not None]
    assert decided, "no game reached a conclusion"


def test_eliminations_are_recorded(result):
    """A regression guard.

    The observer watched ``PLAYER_LOST``; the engine emits
    ``PLAYER_LEFT_GAME``. Every game reported zero eliminations while plainly
    having a winner, and nothing failed - the report just quietly said nothing
    about how anyone lost.
    """
    decided = [r for r in result.records if r.winner is not None]
    assert any(r.eliminations for r in decided)
    for record in decided:
        for turn, player, reason in record.eliminations:
            assert turn > 0
            assert 0 <= player < 4
            assert reason


def test_the_commander_lands_and_the_turn_is_recorded(result):
    landed = [
        r.commander_landed[0] for r in result.records if r.commander_landed[0]
    ]
    assert landed, "the commander never resolved in any game"
    assert all(turn > 0 for turn in landed)


def test_each_player_is_sampled_on_their_own_turn(result):
    """One sample per player per turn *they* took, numbered by their own turns.

    Sampling everyone at everyone's turn-end catches each player at a
    different point in their own cycle, and numbering by the global counter
    puts a four-player game's second round at turns five through eight - so
    averaging over games where the hero sat in different seats turns a clean
    curve into noise. Both were true, and the mana curve came out sawtoothed
    and falling.
    """
    record = result.records[0]
    assert record.turns_series

    per_player = collections.defaultdict(list)
    for snapshot in record.turns_series:
        per_player[snapshot.player].append(snapshot.turn)

    for player, turns in per_player.items():
        assert turns == sorted(turns), f"player {player} sampled out of order"
        assert len(turns) == len(set(turns)), f"player {player} sampled twice a turn"
        assert turns[0] == 1, "a player's first sample is their own turn one"


def test_mana_available_never_goes_backwards(result):
    """It counts every mana source, not the untapped ones.

    Counting untapped sources at end of turn measures what was left over
    after casting, which *falls* as a deck develops - the 10,000-game chart
    showed a mana base peaking on turn four and decaying to nothing while the
    land count kept climbing.

    The deck's only mana sources that can leave play are its mana creatures,
    which die in combat - so mana may fall, but never by more than the
    creature count fell. Lands, which nothing in these decks removes, never
    fall at all.
    """
    record = max(result.records, key=lambda r: r.turns)
    hero = [s for s in record.turns_series if s.player == 0]
    assert len(hero) >= 3
    lands = [s.lands for s in hero]
    assert lands == sorted(lands), f"lands went backwards: {lands}"
    for before, after in zip(hero, hero[1:]):
        lost_mana = before.mana_available - after.mana_available
        lost_creatures = before.creatures - after.creatures
        assert lost_mana <= max(0, lost_creatures), (
            f"turn {after.turn}: mana fell by {lost_mana} "
            f"but only {lost_creatures} creatures left play"
        )
    for snapshot in hero:
        assert snapshot.mana_available >= snapshot.lands


def test_the_opening_hand_is_recorded(result):
    for record in result.records:
        assert record.opening_hand
        assert set(record.opening_hand) <= record.drawn


