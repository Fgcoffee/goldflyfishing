"""The dummy-ability backlog, with how much play each shape would unlock.

    python -m mtgfish.tools.dummy_report CENSUS.jsonl.gz      # print it
    python -m mtgfish.tools.dummy_report --run --write        # census now, write the backlog

A dummy is a shape the parser recognises and the engine can't do yet
(``mtgfish.parser.dummies``). This lists every registered shape with the
cards that use it: all of them, and those in the top 1,000 and 5,000 by play
rate, and its status:

- ``recognised``: the parser emits it, the engine skips it;
- ``implemented``: the browser engine carries it out (``IMPLEMENTED_DUMMIES``
  in engine/src/rules/dummies.ts, mirrored by ``dummies.ENGINE_IMPLEMENTED``);
- ``verified``: the correctness agent checked it on real cards
  (``dummies.VERIFIED``).

``--write`` regenerates ``engine/status/dummy_backlog.md``, the one backlog
the parser and rules sessions share, sorted by top-1,000 weight. The parser
regenerates it with every batch; the rules session works from the top.
"""

from __future__ import annotations

import argparse
import gzip
import json
import re
from pathlib import Path

from ..parser.dummies import DUMMIES, ENGINE_IMPLEMENTED, VERIFIED

_MARK = re.compile(r"\(recognised, (?:not implemented yet|done by the engine): ([a-z0-9-]+)\)")

BACKLOG = Path(__file__).resolve().parents[2] / "engine" / "status" / "dummy_backlog.md"


def _empty() -> dict:
    return {"cards": {}, "top1000": set(), "top5000": set()}


def tally_records(records) -> dict[str, dict]:
    """Per dummy name: cards using it (name -> rank), overall and by depth."""
    out: dict[str, dict] = {d.name: _empty() for d in DUMMIES}
    for row in records:
        rank = row.get("rank")
        for ability in row["abilities"]:
            for name in _MARK.findall(ability.get("ir", "")):
                entry = out.setdefault(name, _empty())
                entry["cards"][row["name"]] = rank
                if rank is not None and rank <= 1000:
                    entry["top1000"].add(row["name"])
                if rank is not None and rank <= 5000:
                    entry["top5000"].add(row["name"])
    return out


def tally(path: str) -> dict[str, dict]:
    with gzip.open(path, "rt", encoding="utf-8") as handle:
        return tally_records(json.loads(line) for line in handle)


def status(name: str) -> str:
    if name in VERIFIED:
        return "verified"
    if name in ENGINE_IMPLEMENTED:
        return "implemented"
    return "recognised"


def _order(counts: dict) -> list[str]:
    return sorted(
        counts, key=lambda n: (-len(counts[n]["top1000"]), -len(counts[n]["top5000"]), -len(counts[n]["cards"]), n)
    )


def _samples(entry: dict, k: int = 3) -> list[str]:
    ranked = sorted(entry["cards"].items(), key=lambda item: (item[1] is None, item[1] or 0, item[0]))
    return [name for name, _ in ranked[:k]]


def markdown(counts: dict) -> str:
    needs = {d.name: d for d in DUMMIES}
    lines = [
        "# Dummy backlog (shared by the parser and rules sessions)",
        "",
        "Generated by `python -m mtgfish.tools.dummy_report --run --write` (parser session, with every",
        "batch). Each row is a shape the parser recognises (`mtgfish/parser/dummies.py`) with what the",
        "engine needs to carry it out. Sorted by how many top-1,000 cards use it; the rules session works",
        "from the top. Status: `recognised` (engine skips it), `implemented` (`IMPLEMENTED_DUMMIES`),",
        "`verified` (checked on real cards by the correctness agent).",
        "",
        "| dummy | status | top 1,000 | top 5,000 | all | samples | what the engine needs |",
        "|---|---|---|---|---|---|---|",
    ]
    for name in _order(counts):
        entry = counts[name]
        dummy = needs.get(name)
        what = (dummy.needs + (f" (CR {dummy.rule})" if dummy.rule else "")) if dummy else "(not in the registry)"
        lines.append(
            f"| `{name}` | {status(name)} | {len(entry['top1000'])} | {len(entry['top5000'])} |"
            f" {len(entry['cards'])} | {', '.join(_samples(entry))} | {what} |"
        )
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("census", nargs="?", help="a census .jsonl.gz (else --run)")
    parser.add_argument("--run", action="store_true", help="run the census now")
    parser.add_argument("--write", action="store_true", help=f"write {BACKLOG.name}")
    parser.add_argument("--jobs", type=int, default=None)
    args = parser.parse_args(argv)
    if args.run:
        from .census import run_census

        counts = tally_records(run_census(jobs=args.jobs))
    elif args.census:
        counts = tally(args.census)
    else:
        parser.error("give a census file or --run")
    text = markdown(counts)
    if args.write:
        BACKLOG.write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {BACKLOG}")
    else:
        print(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
