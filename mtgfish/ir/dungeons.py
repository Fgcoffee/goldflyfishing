"""The rules' dungeons (CR 309) as IR, for the TypeScript engine.

Python reads a dungeon's room graph from its oracle text and parses each
room's effect while the game runs (``rules/cr300_card_types/cr309_dungeons``).
The browser has neither the card database nor the parser, so the same
definitions are exported here: ``python -m mtgfish.tools.ir_export
dungeons`` writes ``schema/dungeons.json`` and the generated
``engine/src/ir/dungeons.ts``. Each dungeon is what ``dungeon_from_card``
builds - name, printed face, entry quality, rooms with their arrows, and
one room ability per room - encoded by the IR codec.
"""

from __future__ import annotations

import json

from .codec import IR_VERSION, encode


def dungeon_documents(db) -> list[dict]:
    """Every dungeon the rules name that the card database has, in the
    rules' order (CR 309.2), including ones whose text gives no usable room
    graph (``mappable`` false; the engine never offers those)."""
    from ..rules.cr300_card_types.cr309_dungeons import load_dungeons

    out = []
    for dungeon in load_dungeons(db):
        out.append(
            {
                "name": dungeon.name,
                "oracle_id": dungeon.oracle_id,
                "entry_quality": dungeon.entry_quality,
                "mappable": dungeon.is_mappable,
                "bottommost": dungeon.bottommost,
                "face": encode(dungeon.face),
                "rooms": [
                    {"name": room.name, "effect_text": room.effect_text, "leads_to": list(room.leads_to)}
                    for room in dungeon.rooms
                ],
                "abilities": [encode(ability) for ability in dungeon.abilities],
            }
        )
    return out


def dungeons_json(db) -> str:
    return json.dumps({"ir_version": IR_VERSION, "dungeons": dungeon_documents(db)}, indent=1, ensure_ascii=False) + "\n"


def dungeons_typescript(db) -> str:
    """The generated engine module: the same data as ``dungeons.json``."""
    body = json.dumps(dungeon_documents(db), indent=1, ensure_ascii=False)
    return (
        "// Generated by `python -m mtgfish.tools.ir_export dungeons` from the card\n"
        "// database (mtgfish/ir/dungeons.py). Do not edit.\n"
        "// The rules' dungeons (CR 309.2) as IR: rooms, arrows, room abilities.\n\n"
        'import type { Ability, FaceDef } from "./types";\n\n'
        "export interface DungeonRoom {\n"
        "  readonly name: string;\n"
        "  readonly effect_text: string;\n"
        "  readonly leads_to: readonly number[];\n"
        "}\n\n"
        "export interface DungeonDef {\n"
        "  readonly name: string;\n"
        "  readonly oracle_id: string;\n"
        "  /** CR 701.49d: the quality that alone lets a player enter it; empty for any venture. */\n"
        "  readonly entry_quality: string;\n"
        "  /** One bottommost room, every room reachable; never offered otherwise. */\n"
        "  readonly mappable: boolean;\n"
        "  readonly bottommost: number;\n"
        "  readonly face: FaceDef;\n"
        "  readonly rooms: readonly DungeonRoom[];\n"
        "  /** One room ability per room, in room order (CR 309.4c). */\n"
        "  readonly abilities: readonly Ability[];\n"
        "}\n\n"
        f"export const DUNGEONS: readonly DungeonDef[] = {body} as unknown as readonly DungeonDef[];\n"
    )
